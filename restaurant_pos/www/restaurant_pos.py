"""Page controller for the cashier SPA.

Its only job is `no_cache`, and that one flag is load-bearing.

Frappe caches a rendered www page in redis under its path alone — no user and
no session in the key (`website/utils.py:cache_html`) — while the CSRF token is
injected by Jinja *inside* that cached HTML. Cached, the page hands whoever
loaded it first their token, and every other terminal inherits it: if that
first visitor was signed out the token is empty and no till can write anything.

The equivalent `<!-- no-cache -->` comment in the HTML is deprecated, and the
HTML is generated by `frontend/vite.config.ts` anyway. Declaring it here keeps
the decision in tracked source.

**The filename is not a typo.** The page is served at `/restaurant-pos` from
`restaurant-pos.html`, but Frappe looks for its controller with the hyphens
replaced by underscores (`template_page.py:set_pymodule`). Named with a hyphen,
this file is silently ignored and the page goes back to being cached.

Refs: D-030, D-031
"""

